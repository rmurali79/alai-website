// Writes deploy/cloud-init.yaml: the setup the new Hetzner server runs on its
// first start. It carries a copy of deploy/Caddyfile, so run this after
// changing the Caddyfile (npm run deploy:cloud-init). With --check it only
// confirms the copy is current and that the Caddyfile's security policy allows
// the layout's inline script, which `npm run check` does.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'deploy/cloud-init.yaml');
const indent = (text, n) => text.trimEnd().split('\n').map((l) => (l ? ' '.repeat(n) + l : '')).join('\n');

const caddyfile = await readFile(path.join(root, 'deploy/Caddyfile'), 'utf8');
const yaml = `#cloud-config
# First-start setup for the alai-labs.com server (Ubuntu 24.04 on Hetzner Cloud).
# Generated by scripts/cloud-init.mjs from deploy/Caddyfile; do not edit by hand.
# Paste this into "Cloud config" when creating the server, after replacing
# PASTE_DEPLOY_PUBLIC_KEY_HERE with the deploy key's public line
# (see docs/operations/hetzner.md).

package_update: true
package_upgrade: true
packages:
  - debian-keyring
  - debian-archive-keyring
  - apt-transport-https
  - curl
  - gnupg
  - rsync
  - ufw
  - fail2ban
  - unattended-upgrades

users:
  - default
  - name: deploy
    gecos: Website deploys from GitHub
    shell: /bin/bash
    lock_passwd: true
    ssh_authorized_keys:
      - PASTE_DEPLOY_PUBLIC_KEY_HERE

write_files:
  - path: /etc/ssh/sshd_config.d/10-alai.conf
    content: |
      PasswordAuthentication no
      KbdInteractiveAuthentication no
      PermitRootLogin prohibit-password
  - path: /etc/systemd/system/caddy.service.d/site.conf
    content: |
      [Service]
      # The address the site answers on. On first start this becomes
      # <ip-with-dashes>.sslip.io, a free name for the server's IP that gets
      # real HTTPS. Change to alai-labs.com when the domain moves, then:
      # systemctl daemon-reload && systemctl restart caddy
      Environment=SITE_DOMAIN=PENDING
  - path: /var/www/alai/releases/initial/index.html
    content: |
      <!doctype html><html lang="en"><title>Alai Labs</title><p>The site is being set up.</p></html>
  - path: /root/Caddyfile.alai
    content: |
${indent(caddyfile, 6)}

runcmd:
  - curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/gpg.key | gpg --dearmor -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
  - curl -1sLf https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt -o /etc/apt/sources.list.d/caddy-stable.list
  - apt-get update
  - DEBIAN_FRONTEND=noninteractive apt-get install -y caddy
  - ln -sfn releases/initial /var/www/alai/current
  - chown -R deploy:deploy /var/www/alai
  - install -m 644 /root/Caddyfile.alai /etc/caddy/Caddyfile
  - caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile
  - IP=$(curl -fsS http://169.254.169.254/hetzner/v1/metadata/public-ipv4) && sed -i "s/SITE_DOMAIN=PENDING/SITE_DOMAIN=$(echo "$IP" | tr . -).sslip.io/" /etc/systemd/system/caddy.service.d/site.conf
  - systemctl daemon-reload
  - systemctl restart caddy
  - ufw allow OpenSSH
  - ufw allow 80/tcp
  - ufw allow 443/tcp
  - ufw allow 443/udp
  - ufw --force enable
  - systemctl restart ssh
`;

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== yaml) {
    console.error('deploy/cloud-init.yaml is out of date with deploy/Caddyfile. Run: npm run deploy:cloud-init');
    process.exit(1);
  }
  const layout = await readFile(path.join(root, 'src/layout.html'), 'utf8');
  for (const [, code] of layout.matchAll(/<script>([\s\S]*?)<\/script>/g)) {
    const hash = `'sha256-${createHash('sha256').update(code).digest('base64')}'`;
    if (!caddyfile.includes(hash)) {
      console.error(`deploy/Caddyfile script-src is missing ${hash} for the inline script in src/layout.html`);
      process.exit(1);
    }
  }
  console.log('deploy/cloud-init.yaml matches deploy/Caddyfile, and its policy allows the inline script');
} else {
  await writeFile(target, yaml);
  console.log('Wrote deploy/cloud-init.yaml');
}
